/**
 * Extracts visible plain text from legal pages for the client-side search index.
 * Run after legal copy changes: node scripts/generate-legal-search-text.mjs
 */
import fs from "node:fs";
import path from "node:path";

const root = path.join(import.meta.dirname, "..");

function decodeEntities(text) {
  return text
    .replace(/&ldquo;|&rdquo;/g, '"')
    .replace(/&lsquo;|&rsquo;/g, "'")
    .replace(/&amp;/g, "&")
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&#123;/g, "{")
    .replace(/&#125;/g, "}");
}

/** Rough JSX → plain text for search indexing (mirrors on-page copy). */
export function extractVisibleTextFromTsx(source) {
  let text = source;
  text = text.replace(/^[\s\S]*?export default function\s+\w+/m, "");
  text = text.replace(/\/\*[\s\S]*?\*\//g, " ");
  text = text.replace(/\/\/[^\n]*/g, " ");
  text = text.replace(/import\s+[\s\S]*?from\s+["'][^"']+["'];?/g, " ");
  text = text.replace(/<script[\s\S]*?<\/script>/gi, " ");
  text = text.replace(/\{`[\s\S]*?`\}/g, " ");
  text = text.replace(/\{[^}]*\}/g, " ");
  text = text.replace(/<[^>]+>/g, " ");
  text = decodeEntities(text);
  text = text.replace(/\)\s*>\s*/g, " ");
  text = text.replace(/\s+/g, " ").trim();
  return text;
}

function readEngagementRaw() {
  const rawPath = path.join(
    root,
    "src/app/standard-terms-and-conditions-of-engagement/engagement-terms.raw.txt",
  );
  return fs.readFileSync(rawPath, "utf8").replace(/\s+/g, " ").trim();
}

function readTsxPage(relPath) {
  const full = path.join(root, relPath);
  return extractVisibleTextFromTsx(fs.readFileSync(full, "utf8"));
}

const bodies = {
  privacy: readTsxPage("src/app/privacy-policy/page.tsx"),
  cookies: readTsxPage("src/app/cookies-policy/page.tsx"),
  disclaimer: readTsxPage("src/app/disclaimer/page.tsx"),
  terms: readTsxPage("src/app/terms-and-conditions/page.tsx"),
  engagement: readEngagementRaw(),
};

const outPath = path.join(root, "src/lib/legal-page-search-content.ts");
const file = `/* eslint-disable -- generated by scripts/generate-legal-search-text.mjs */
/** Plain-text mirrors of legal page copy for search indexing. Regenerate with: npm run generate:legal-search-text */

export function buildPrivacyPageSearchBody(): string {
  return ${JSON.stringify(bodies.privacy)};
}

export function buildCookiesPageSearchBody(): string {
  return ${JSON.stringify(bodies.cookies)};
}

export function buildDisclaimerPageSearchBody(): string {
  return ${JSON.stringify(bodies.disclaimer)};
}

export function buildTermsPageSearchBody(): string {
  return ${JSON.stringify(bodies.terms)};
}

export function buildEngagementPageSearchBody(): string {
  return ${JSON.stringify(bodies.engagement)};
}
`;

fs.writeFileSync(outPath, file, "utf8");
console.log(`Wrote ${outPath}`);
